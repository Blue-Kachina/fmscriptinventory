                                        <p>FileMaker&#160;Pro defines certain constants you can use by name in any calculation formula. Many constants are defined as values for a parameter in specific functions, such as the <code>JSONObject</code> value for the <code>type</code> parameter of the JSONSetElement function. Other constants are for general use, such as the Boolean values <code>True</code> and <code>False</code>. Some keywords like <code>ROWID</code> are reserved because of their special use in SQL and OData; in FileMaker formulas, they are equivalent to  specific Get functions.</p>
                                        <p>Treat these as reserved words and avoid using them as field or table names. See <a href="reserved-word-symbol-for-field-or-table.html" class="MCXref xref">Using a reserved word or symbol for a field or table name</a>.</p>
