                                        <h2 class="notes-head" data-mc-autonum="Notes"><span class="autonumber"><span>Notes</span></span>&#160;</h2>
                                        <ul>
                                            <li><code>accuracy</code> is a number that represents a distance in meters. The default value for <code>accuracy</code> is 100 meters.</li>
                                            <li><code>timeout</code> is a number that represents the longest time (in seconds) it will take to get the data. The default value for <code>timeout</code> is 10; the maximum value is 600.</li>
                                            <li>The default value for <code>forPastSeconds</code> is the number of seconds since midnight.</li>
                                            <li>FileMaker&#160;Go returns an empty string if the sensor is not available for the device.</li>
                                            <li>The values for <code>location</code> are the same as for the <a class="LinktoFunction MCXref xref xrefLinktoFunction" href="location.html">Location function</a>.</li>
                                            <li>The values for <code>locationValues</code> are the same as for the <a class="LinktoFunction MCXref xref xrefLinktoFunction" href="locationvalues.html">LocationValues function</a>.</li>
                                        </ul>
