                                        <h2 class="notes-head" data-mc-autonum="Notes"><span class="autonumber"><span>Notes</span></span>&#160;</h2>
                                        <ul>
                                            <li>Barcodes and signatures are not considered images.</li>
                                            <li>The <code>internalSize</code> can be much smaller than the <code>fileSize</code> (for example, container fields set up for open or secure storage, file references, or compressed files) or much larger than the <code>fileSize</code> (for example, container fields created by plug-ins). </li>
                                            <li>Using the attribute <code>MD5 </code>allows you to prevent the insertion of duplicated files into a container field regardless of the filename.</li>
                                            <li>For the group attributes <code>general</code>, <code>audio</code>,<code> image</code>,<code> photo</code>, and <code>all</code>, attributes are displayed in the format <code>attributeName: attributeValue</code> with one attribute per line. Some attributes are displayed differently in order to fit the attribute on one line:<ul><li><code>externalFiles</code>. Displays only the number of external files.</li><li><code>transparency</code>. Displays <strong>1 (True)</strong><strong> </strong>or <strong>0 (False)</strong>.</li><li><code>coverArt</code>. Displays <strong>png </strong>or <strong>jpg </strong>depending on the type of image.</li><li><code>bitRate</code>. Displays <strong>kbps </strong>after the number. If an audio uses a variable bit rate, (VBR) is appended to the result. For example: Bit Rate: 247 kbps (VBR).</li><li><code>year</code>.<code> </code>Date information may be returned in parentheses after the year. For example: <strong>Year: 2019 (11/10/2019)</strong>.</li></ul></li>
                                            <li>Each returned value, except the last, ends with a carriage return.</li>
                                            <li>To minimize the frequency with which FileMaker&#160;Pro analyzes container data, use GetContainerAttribute in a field''s auto-enter calculation and deselect <strong>Do not replace existing value of field (if any)</strong>. In this case, GetContainerAttribute will update only when the contents of the specified container field change. If GetContainerAttribute is used in a calculation field definition, the calculation may update each time the current record changes, reducing the performance of your custom app.</li>
                                        </ul>
