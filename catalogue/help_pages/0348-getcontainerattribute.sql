                                        <h1 class="func">GetContainerAttribute</h1>
                                        <p class="ref-purpose-func"><span class="mc-variable ui-strings-functions.kDBGetContainerAttrOp variable">Returns the file metadata of the specified container field.</span>
                                        </p>
                                        <h2 class="ref-format-head" data-mc-autonum="Format"><span class="autonumber"><span>Format</span></span>&#160;</h2><pre class="ref-format">GetContainerAttribute ( field ; attributeName )</pre>
                                        <h2 class="ref-param-head" data-mc-autonum="Parameters"><span class="autonumber"><span>Parameters</span></span>&#160;</h2>
                                        <p><code>field</code> - any expression that returns container data.</p>
                                        <p><code>attributeName</code> - the name of a supported attribute (see below).</p>
                                        <h2 class="ref-return-head" data-mc-autonum="Data type returned"><span class="autonumber"><span>Data type returned</span></span>&#160;</h2>
                                        <p>text, number, date, time, timestamp, container</p>
                                        <h2 class="ref-orig-head" data-mc-autonum="Originated in version"><span class="autonumber"><span>Originated in version</span></span>&#160;</h2>
                                        <p class="or-origin">13.0</p>
                                        <h2 class="ref-desc-head" data-mc-autonum="Description"><span class="autonumber"><span>Description</span></span>&#160;</h2>
                                        <p>Some attributes may not return a result. For example, the values for the latitude and longitude of a photo may not be available, or some audio metadata like album art may not be available because the metadata is stored outside the audio file. Some individual attributes in the group attribute <code>all</code> may not be applicable in some circumstances.</p>
                                        <p>In addition, when databases are hosted on Windows or Cloud and accessed via REST APIs, some attributes from the GetContainerAttribute function (for example, <code>photo</code>, <code>created</code>, <code>modified</code>, and <code>all</code>) may return invalid values.&#160;
